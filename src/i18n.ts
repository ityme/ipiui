export function translate(language: PanelLanguage, key: MessageKey, values: Record<string, string> = {}): string {
	return (language === "zh" ? zh[key] : en[key]).replace(/\{(\w+)\}/g, (token, name: string) => values[name] ?? token);
}

export function languageName(language: PanelLanguage): string { return language === "zh" ? "简体中文" : "English"; }
